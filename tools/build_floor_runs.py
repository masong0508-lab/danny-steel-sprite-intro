#!/usr/bin/env python3
"""Lossless projection tables for quarter-tile floor scans and skyline."""
from pathlib import Path
import sys

def texel(x,y):
    v=((x+31)*1664525+(y+79)*1013904223)&0xffffffff
    v=((v^(v>>13))*2246822519)&0xffffffff
    return v^(v>>11)
def line(values):
    return " {"+",".join(map(str,values))+"},\n"
runs=[]
for negative in range(2):
    group=[]
    for y in range(80,140):
        dist=min(2304,13500//(y-75))
        unit=dist*768//480
        step=2 if y<98 else 1
        def sample(x):
            return (-(x-120)*unit+255 if negative else (x-120)*unit)>>12
        row=[240]*240
        for x in range(0,240,step):
            end=x+step
            while end<240 and sample(end)==sample(x):
                end+=step
            row[x]=end
        group.append(row)
    runs.append(group)
dither=[]
for far in range(2):
    row=[]
    for n in range(400):
        k=(17-n%17)%17
        if far and k&1: k+=17
        row.append(k)
    dither.append(row)
sky=[]
for i in range(-2,19):
    ht=17+texel(i+33,23)%22
    row=[ht]
    for w in range(3,21,7):
        mask=0
        for j,h in enumerate(range(7,ht-2,9)):
            if texel(i+41+w,h+35)&3: mask|=1<<j
        row.append(mask|(((5-(i+w)%5)%5)<<4))
    sky.append(row)
result="""/* Generated by tools/build_floor_runs.py: exact projected texel run ends,
   dither distances and fixed skyline materials. Immutable cartridge data. */
"""
result+="static const uint8_t hd_floor_run_next[2][60][240]={\n"
for group in runs:
    result+=" {\n"+"".join(map(line,group))+" },\n"
result+="};\nstatic const uint8_t hd_floor_dither_skip[2][400]={\n"
result+="".join(map(line,dither))+"};\n"
result+="static const uint8_t hd_skyline_material[21][4]={\n"
result+="".join(map(line,sky))+"};\n"
Path(sys.argv[1] if len(sys.argv)>1 else "src/hd_floor_runs.inc").write_text(result)
