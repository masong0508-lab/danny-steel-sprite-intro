#!/usr/bin/env python3
"""Bake exactly the authored facade, distance tint, tree and shop-sign shader."""
import re
import sys
from pathlib import Path
source = Path("src/hd_facade_art.c").read_text()
part = source.split("fronts[2][8][640]", 1)[1].split("const uint8_t *hd_facade_texture", 1)[0]
art = list(map(int, re.findall(r"\b\d+\b", part.split("=",1)[1])))
assert len(art)==10240
# Palette indices are the stable HD enum (32..63).
dim = [32,32,34,35,36,37,37,39,40,40,41,37,43,45,63,47,47,34,54,51,51,52,54,43,56,38,59,59,60,60,62,50]
glyph = [[7,5,7,4,4],[7,5,5,5,7],[7,2,2,2,2],[5,5,7,5,5],[7,4,6,4,7],[2,5,7,5,5],[6,5,5,5,6],[7,4,7,1,7]]
def texel(x,y):
    v=((x+31)*1664525+(y+79)*1013904223)&0xffffffff
    v=((v^(v>>13))*2246822519)&0xffffffff
    return v^(v>>11)
def sign(u,v):
    if not (48<=u<208 and 64<=v<116): return -1
    if v<70 or v>=110: return 52
    if u<55 or u>=202 or v<73 or v>=104: return 51
    if 76<=v<96 and 64<=u<192:
        c,row=(u-64)>>2,(v-76)>>2
        if (c&3)<3 and (glyph[c>>2][row]>>(2-(c&3)))&1: return 55
    return 51
def shade(side,variant,u,v,far,shop):
    c=art[((side*8+variant)*40+((v*40)>>8))*16+(u>>4)]
    if far: c=dim[c-32]
    s=sign(u,v) if shop else -1
    return s if s>=0 else c
def tree(u,v):
    if v>225 and (u&15)==1: return 37
    if v>178 and 91<u<162: return 54
    return 53 if (texel(u>>3,v>>3)&3)==0 else 52
index,strips,seen=[],[],{}
def add(fn):
    key=bytes(fn(v) for v in range(256))
    assert all(32<=c<64 for c in key)
    if key not in seen:
        seen[key]=len(strips)
        strips.append(key)
    index.append(seen[key])
for s in range(2):
    for n in range(8):
        for far in range(2):
            for u in range(0,256,16):
                add(lambda v:shade(s,n,u,v,far,False))
for u in range(256):
    add(lambda v:tree(u,v))
for s in range(2):
    for far in range(2):
        for u in range(256):
            add(lambda v:shade(s,7,u,v,far,True))
heights=sorted({2*(min(150,20800//(min(2300,i*32)+60))//2) for i in range(1,73)})
offsets,scale=[65535]*76,[]
for h in heights:
    offsets[h//2]=len(scale)
    scale.extend(y*256//h for y in range(h))
def rows(v,n):
    return "".join(" "+",".join(map(str,v[i:i+n]))+",\n" for i in range(0,len(v),n))
def quote(s):
    return ' "'+''.join(('\\' if c in (34,63,92) else '')+chr(c) for c in s)+'",\n'
result="""/* Generated by tools/build_wall_shades.py. Exact indexed wall shades;
   identical 256-sample vertical strips are shared. No new runtime RAM. */
"""
result+="static const uint16_t hd_wall_strip_index[1792]={\n"+rows(index,24)+"};\n"
result+=f"static const uint8_t hd_wall_shades[{len(strips)}][256]={{\n"+''.join(map(quote,strips))+"};\n"
result+="static const uint16_t hd_wall_scale_offset[76]={\n"+rows(offsets,16)+"};\n"
result+=f"static const uint8_t hd_wall_scale[{len(scale)}]={{\n"+rows(scale,24)+"};\n"
Path(sys.argv[1] if len(sys.argv)>1 else "src/hd_wall_shades.inc").write_text(result)
