#!/usr/bin/env python3
"""Reproduce three DMA-friendly alignments of the exact neutral skyline."""
import re
import sys
from pathlib import Path
src=Path("src/hd_skyline_rom.inc").read_text()
base=list(map(int,re.findall(r"\d+",src.split("hd_sky_pixels[16512]",1)[1].split("{",1)[1].split("};",1)[0])))
assert len(base)==344*48
def rows(a):
    return "".join(" "+",".join(map(str,a[i:i+24]))+",\n" for i in range(0,len(a),24))
out="""/* Generated by tools/build_skyline_dma.py. Three additional alignments
   of the original neutral sky; each row ends with unused zero padding. */
"""
out+="static const uint8_t hd_sky_shifted[3][16512] __attribute__((aligned(4)))={\n"
for shift in range(1,4):
    data=[base[y*344+x+shift] if x+shift<344 else 0 for y in range(48) for x in range(344)]
    out+=" {\n"+rows(data)+" },\n"
out+="};\n"
Path(sys.argv[1] if len(sys.argv)>1 else "src/hd_skyline_dma.inc").write_text(out)
