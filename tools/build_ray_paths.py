#!/usr/bin/env python3
"""Generate lossless, translation-invariant ray crossing sequences."""
import sys
from pathlib import Path

offsets, pool, seen = [], [], {}
for major in range(8):
    for minor in range(8):
        for speed in range(23):
            a = major * 64 if major < 4 else 255 - (major - 4) * 64
            b = minor * 64 if minor < 4 else 255 - (minor - 4) * 64
            ma = mi = last = 0
            path = []
            for step in range(1, 76):
                aa, bb = (a + 32 * step) >> 8, (b + speed * step) >> 8
                mask = int(aa != ma) + 2 * int(bb != mi)
                if mask:
                    gap = step - last
                    assert 1 <= gap <= 8
                    path.append((mask << 4) | gap)
                    last, ma, mi = step, aa, bb
            path.append(0)
            key = tuple(path)
            if key not in seen:
                seen[key] = len(pool)
                pool.extend(path)
            offsets.append(seen[key])

def rows(values, width):
    return "".join(" " + ",".join(map(str, values[i:i+width])) + ",\n"
                   for i in range(0, len(values), width))

assert len(offsets) == 1472 and len(pool) < 65536
result = """/* Generated by tools/build_ray_paths.py: exact original 75-sample
   quarter-tile ray crossings. Byte = crossed axes in bits 4/5,
   elapsed sample count in low four bits. Zero terminates a path. */
"""
result += "static const uint16_t hd_ray_offsets[1472]={\n" + rows(offsets, 16) + "};\n"
result += f"static const uint8_t hd_ray_paths[{len(pool)}]={{\n" + rows(pool, 24) + "};\n"
Path(sys.argv[1] if len(sys.argv)>1 else "src/hd_ray_paths.inc").write_text(result)
