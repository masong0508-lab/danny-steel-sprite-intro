#!/usr/bin/env python3
"""Encode the authored, settled Potheads set as an immutable ROM word stream.

The live projection remains the source of truth and renders the descent.
This tool evaluates that same portable painter at tick 180, then groups
repeated four-pixel words and literal words. No actor or source-video pixels
enter this data. The decoder paints directly into the existing shared page.
"""
import argparse
import hashlib
import os
from pathlib import Path
import shlex
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
EXPORTER = r'''
#include <stdio.h>
#include "hd_canvas.h"
#include "hd_potheads_set.h"
int main(void){
 uint8_t pixels[HD_BYTES];PotCamera camera=pot_camera(180u);
 pot_scene(pixels,&camera,180u);
 return fwrite(pixels,1,sizeof pixels,stdout)==sizeof pixels?0:1;
}
'''
DECODER = r'''
/* The production page is word-aligned. The byte path also supports host
   callers with an unaligned canvas; neither path allocates or caches RAM.
   noinline keeps this single-call helper in ARM IWRAM. Volatile word stores
   prevent GCC from replacing the short fills with ROM memset calls. */
static HD_CANVAS_CODE __attribute__((noinline)) void pot_scene_fixed(uint8_t *p){
 typedef uint32_t PotWord __attribute__((may_alias));
 const uint32_t *run=pot_set_rle;
 const uint32_t *end=run+sizeof(pot_set_rle)/sizeof(pot_set_rle[0]);
 if((uintptr_t)p&3u){
  while(run!=end){
   unsigned token=*run++,count=token&0x7fffffffu;
   if(token&0x80000000u){
    uint32_t fill=*run++;
    while(count--){
     p[0]=(uint8_t)fill;p[1]=(uint8_t)(fill>>8);
     p[2]=(uint8_t)(fill>>16);p[3]=(uint8_t)(fill>>24);p+=4;
    }
   }else{
    while(count--){
     uint32_t four=*run++;
     p[0]=(uint8_t)four;p[1]=(uint8_t)(four>>8);
     p[2]=(uint8_t)(four>>16);p[3]=(uint8_t)(four>>24);p+=4;
    }
   }
  }
  return;
 }
 volatile PotWord *out=(volatile PotWord *)(void *)p;
 while(run!=end){
  unsigned token=*run++,count=token&0x7fffffffu;
  if(token&0x80000000u){
   uint32_t fill=*run++;
   while(count>=4u){
    out[0]=fill;out[1]=fill;out[2]=fill;out[3]=fill;
    out+=4;count-=4u;
   }
   while(count--)*out++=fill;
  }else{
   while(count>=4u){
    out[0]=run[0];out[1]=run[1];out[2]=run[2];out[3]=run[3];
    out+=4;run+=4;count-=4u;
   }
   while(count--)*out++=*run++;
  }
 }
}
'''


def render_set():
    with tempfile.TemporaryDirectory(prefix="potheads-set-") as temporary:
        directory = Path(temporary)
        source, program = directory / "render.c", directory / "render"
        source.write_text(EXPORTER)
        compiler = shlex.split(os.environ.get("CC", "cc"))
        subprocess.run([*compiler, "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror",
                        "-I", str(ROOT / "src"), str(source),
                        str(ROOT / "src/hd_canvas.c"), "-o", str(program)], check=True)
        pixels = subprocess.check_output([str(program)])
    if len(pixels) != 240 * 160 or any(pixel >= 64 for pixel in pixels):
        raise ValueError("The projected set must contain 38400 native palette indices")
    return pixels


def encode(pixels):
    words = struct.unpack("<9600I", pixels)
    stream, at = [], 0
    while at < len(words):
        end = at + 1
        while end < len(words) and words[end] == words[at]:
            end += 1
        if end - at >= 3:
            stream.extend((0x80000000 | (end - at), words[at]))
            at = end
        else:
            start, at = at, end
            while at < len(words):
                end = at + 1
                while end < len(words) and words[end] == words[at]:
                    end += 1
                if end - at >= 3:
                    break
                at = end
            stream.extend((at - start, *words[start:at]))
    return stream


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    pixels = render_set()
    stream = encode(pixels)
    header = ["#pragma once", '#include "hd_canvas.h"', "",
              "/* Generated by tools/build_potheads_set.py from the live projected set.",
              "   Camera settles at tick 180; this exact set remains immutable afterward.",
              f"   Pixel SHA256: {hashlib.sha256(pixels).hexdigest()}",
              "   A control word stores a positive four-pixel count. Bit31 selects",
              "   one repeated word; otherwise the count literal words follow.",
              f"   {len(stream) * 4} ROM bytes decode directly into the existing 38400-byte page. */",
              "static const uint32_t pot_set_rle[]={"]
    for at in range(0, len(stream), 8):
        header.append(" " + ",".join(f"0x{word:08x}u" for word in stream[at:at + 8]) + ",")
    header.extend(("};", DECODER))
    args.output.write_text("\n".join(header))
    print(f"Potheads set: 38400 pixels → {len(stream) * 4} ROM bytes; {args.output}")


if __name__ == "__main__":
    main()
