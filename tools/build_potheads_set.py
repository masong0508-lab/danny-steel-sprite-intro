#!/usr/bin/env python3
"""Pack the authored settled Potheads set as DMA-ready immutable ROM words.

The live projection remains the source of truth and renders the descent.
No actor or source-video pixels enter this data. No second RAM page.
"""
import argparse
import hashlib
import os
from pathlib import Path
import shlex
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
EXPORTER = r'''
#include <stdio.h>
#include "hd_canvas.h"
#include "hd_potheads_set.h"
int main(void){
 uint8_t pixels[HD_BYTES];PotCamera camera=pot_camera(180u);
 pot_scene(pixels,&camera,180u);
 return fwrite(pixels,1,sizeof pixels,stdout)==sizeof pixels?0:1;
}
'''
DECODER = r'''
/* DMA3 is exclusively owned by the main-thread renderer during gameplay.
   The IRQ only records keys, updates PSG, and publishes completed pages.
   ROM -> aligned EWRAM is a single immediate word transfer; no new RAM
   buffer, IRQ changes, or VRAM writes. Host and unaligned callers use the
   exact same source words through a portable byte path. */
static HD_CANVAS_CODE __attribute__((noinline)) void pot_scene_fixed(uint8_t *p){
#if defined(__arm__) && !defined(HOST_TEST)
 uintptr_t dest=(uintptr_t)p;
 if(!(dest&3u)&&dest>=0x02000000u&&dest<=0x02040000u-HD_BYTES){
  volatile uint32_t *dma=(volatile uint32_t *)0x040000D4u;
  while(dma[2]&0x80000000u){}
  dma[2]=0;
  dma[0]=(uint32_t)(uintptr_t)pot_set_words;
  dma[1]=(uint32_t)dest;
  __asm__ volatile("" ::: "memory");
  dma[2]=0x84000000u|(HD_BYTES/4u);
  while(dma[2]&0x80000000u){}
  __asm__ volatile("" ::: "memory");
  return;
 }
#endif
 for(unsigned i=0;i<HD_BYTES/4u;i++){
  uint32_t four=pot_set_words[i];
  p[0]=(uint8_t)four;p[1]=(uint8_t)(four>>8);
  p[2]=(uint8_t)(four>>16);p[3]=(uint8_t)(four>>24);p+=4;
 }
}
'''


def render_set():
    with tempfile.TemporaryDirectory(prefix="potheads-set-") as temporary:
        directory = Path(temporary)
        source, program = directory / "render.c", directory / "render"
        source.write_text(EXPORTER)
        compiler = shlex.split(os.environ.get("CC", "cc"))
        subprocess.run([*compiler, "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror",
                        "-I", str(ROOT / "src"), str(source),
                        str(ROOT / "src/hd_canvas.c"), "-o", str(program)], check=True)
        pixels = subprocess.check_output([str(program)])
    if len(pixels) != 240 * 160 or any(pixel >= 64 for pixel in pixels):
        raise ValueError("The projected set must contain 38400 native palette indices")
    return pixels


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    pixels = render_set()
    words = struct.unpack("<9600I", pixels)
    header = ["#pragma once", '#include "hd_canvas.h"', "",
              "/* Generated by tools/build_potheads_set.py from the live projected set.",
              "   Camera settles at tick 180; this exact set remains immutable afterward.",
              f"   Pixel SHA256: {hashlib.sha256(pixels).hexdigest()}",
              "   38400 ROM bytes, word-aligned for immediate DMA into the shared page. */",
              "static const uint32_t pot_set_words[]={"]
    for at in range(0, len(words), 8):
        header.append(" " + ",".join(f"0x{word:08x}u" for word in words[at:at + 8]) + ",")
    header.extend(("};", DECODER))
    args.output.write_text("\n".join(header))
    print(f"Potheads set: 38400 DMA-ready ROM bytes; {args.output}")


if __name__ == "__main__":
    main()
