#!/usr/bin/env python3
"""Bake byte-exact sheared, height-scaled facade rows from the existing art."""
from pathlib import Path
import re, sys
source=Path("src/hd_facade_art.c").read_text()
start=source.index("={",source.index("static const uint8_t fronts"))+2
end=source.index("const uint8_t *hd_facade_texture")
# Ignore the generated include and all implementation after the art.
raw=source[start:end].split("};",1)[0]
values=list(map(int,re.findall(r"\b\d+\b",raw)))
assert len(values)==10240 and all(32<=v<=63 for v in values)
heights=[27,32,36,40,42,44,46,52]
pixels=[]; offsets=[]; spans=[]; span_offsets=[]
for h in heights:
    offsets.append(len(pixels)); span_offsets.append(len(spans))
    for side in range(2):
        for y in range(h+8):
            cols=[x for x in range(16) if 0<=y-(8-x//2 if side else x//2)<h]
            spans.append((cols[0]//2)|(((cols[-1]+1)//2)<<4) if cols else 0)
        for variant in range(8):
            for y in range(h+8):
                for x in range(16):
                    row=y-(8-x//2 if side else x//2)
                    pixels.append(values[(side*8+variant)*640+(row*40//h)*16+x] if 0<=row<h else 0)
def array(name, values, kind="uint8_t"):
    return f"static const {kind} {name}[{len(values)}]={{\n"+''.join(" "+",".join(map(str,values[i:i+24]))+",\n" for i in range(0,len(values),24))+"};\n"
slots=[0]*53
for i,h in enumerate(heights):slots[h]=i+1
out="// Generated by tools/build_facade_rasters.py; do not edit.\n"
out+=array("facade_height_id",slots)+array("facade_raster_offset",offsets,"uint32_t")+array("facade_span_offset",span_offsets,"uint16_t")+array("facade_span_codes",spans)
out+=f"static const uint8_t facade_rasters[{len(pixels)+1}] __attribute__((aligned(4)))=\n"
for i in range(0,len(pixels),64):
    out+=' "'+''.join(f"\\x{n:02x}" for n in pixels[i:i+64])+'"\n'
out+=";\n"
Path(sys.argv[1] if len(sys.argv)>1 else "src/hd_facade_rasters.inc").write_text(out)
