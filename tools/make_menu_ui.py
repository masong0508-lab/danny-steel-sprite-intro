"""Builds src/menu_ui_data.c: 4bpp OBJ tiles for the menu labels and the 3-chevron cursor.  Run from project root:  python3 tools/make_menu_ui.py
Layout of ui_tiles (tile = 8 words):
  label i (0..5) = 16 tiles at i*16: two 32x16 sprites (left half = tiles 0-7, right half = tiles 8-15), text centred in a 64x16 canvas
  cursor         = 8 tiles at 96:   one 16x32 sprite, three chevrons (colour index 1,2,3) + dark shadow (index 4)
Label colours: 1 = white, 2..4 = anti-alias steps (the game fades them toward the background grey with the palette)."""
import numpy as np
from PIL import Image, ImageDraw, ImageFont
LABELS = ['NEW GAME', 'LOAD', 'ERASE', 'SLOT 1', 'SLOT 2', 'BACK']
FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed.ttf'
SS = 8; SIZE = 11; BASE = 12                       # supersample, font px, baseline row inside the 16-row canvas (cap height ~8 -> rows 4..11)
font = ImageFont.truetype(FONT, SIZE * SS)

def label(txt):
    big = Image.new('L', (64 * SS, 16 * SS), 0); d = ImageDraw.Draw(big)
    w = d.textlength(txt, font=font); d.text(((64 * SS - w) / 2, BASE * SS), txt, font=font, fill=255, anchor='ls')
    cov = np.array(big.resize((64, 16), Image.BOX), np.float32) / 255
    idx = np.zeros((16, 64), np.uint8)
    idx[cov >= 0.125] = 4; idx[cov >= 0.375] = 3; idx[cov >= 0.625] = 2; idx[cov >= 0.875] = 1
    return idx

def tiles(img, w, h):                              # img = h x w palette indices -> 1-D mapped 4bpp tiles, row-major tile order
    out = []
    for ty in range(h // 8):
        for tx in range(w // 8):
            for r in range(8):
                v = 0
                for x in range(8): v |= int(img[ty * 8 + r, tx * 8 + x]) << (4 * x)
                out.append(v)
    return out

words = []
for t in LABELS:
    im = label(t); words += tiles(im[:, :32], 32, 16) + tiles(im[:, 32:], 32, 16)
cur = np.zeros((32, 16), np.uint8)
HALF = [7, 6, 5, 3, 1]                              # flat down-pointing chevron, 5 rows, centred on x=7.5 (widths 15,13,11,7,3)
def chev(top, col):
    for r, hw in enumerate(HALF):
        for x in range(8 - hw - 1, 8 + hw):
            if 0 <= x < 16 and 0 <= top + r < 32: cur[top + r, x] = col
for j in range(3):                                  # shadow first (1 px lower), then the coloured chevron on top
    chev(2 + 10 * j + 1, 4)
for j in range(3):
    chev(2 + 10 * j, 1 + j)
words += tiles(cur, 16, 32)
with open('src/menu_ui_data.c', 'w') as f:
    f.write('// GENERATED by tools/make_menu_ui.py - do not edit\n#include "menu.h"\n')
    f.write('const int ui_tile_words = %d;\n' % len(words))
    f.write('const u32 ui_tiles[%d] = {%s};\n' % (len(words), ','.join('0x%08x' % w for w in words)))
print('tiles', len(words) // 8)
# preview
pv = Image.new('P', (64, 16 * 6 + 32)); pal = [0, 0, 0, 255, 255, 255, 210, 210, 210, 150, 150, 150, 90, 90, 90]
pal += [255, 140, 20, 80, 200, 240, 20, 20, 20]
for i, t in enumerate(LABELS): pv.paste(Image.fromarray(label(t)), (0, i * 16))
pv.putpalette(pal + [0] * (768 - len(pal))); pv.convert('RGB').resize((256, (16 * 6 + 32) * 4), Image.NEAREST).save('/tmp/ui_preview.png')
