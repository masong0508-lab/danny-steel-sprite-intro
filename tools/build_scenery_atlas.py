#!/usr/bin/env python3
"""Reproduce the original skyline and material shader, losslessly."""
import re
import sys
from pathlib import Path
out=Path(sys.argv[1]) if len(sys.argv)>1 else Path("src")
out.mkdir(parents=True,exist_ok=True)
source=Path("src/hd_floor_runs.inc").read_text()
mat=list(map(int,re.findall(r"\d+",source.split("hd_skyline_material[21][4]",1)[1].split("{",1)[1].split("};",1)[0])))
story=Path("src/story.c").read_text()
town=re.findall(r'"([#.,~A-Za-z=]{24})"',story.split("static const char *const town",1)[1].split("char story_tile",1)[0])
assert len(mat)==84 and len(town)==18
W,H,L,T=344,48,-52,32
def panorama(phase):
    p=[17 if T+n//W<54 else 47 if T+n//W<74 else 48 for n in range(W*H)]
    def pixel(x,y,c):
        if L<=x<L+W and T<=y<T+H: p[(y-T)*W+x-L]=c
    def rect(x,y,w,h,c):
        for j in range(max(y,T),min(y+h,T+H)):
            for k in range(max(x,L),min(x+w,L+W)): pixel(k,j,c)
    def line(x,y,xx,yy,c):
        dx,dy=abs(xx-x),abs(yy-y)
        sx,sy=1 if x<xx else -1,1 if y<yy else -1
        e=dx-dy
        while True:
            pixel(x,y,c)
            if x==xx and y==yy: break
            t=2*e
            if t>-dy: e-=dy; x+=sx
            if t<dx: e+=dx; y+=sy
    for i in range(-2,19):
        x,ht=i*23,mat[(i+2)*4]
        rect(x,79-ht,23,ht,39);rect(x+3,79-ht-2,18,2,32)
        line(x-2,79-ht,x+10,73-ht,39);line(x+10,73-ht,x+25,79-ht,39);line(x+1,79-ht,x+21,79-ht,37)
        if i&3==0: rect(x+14,69-ht,3,10,34);rect(x+13,68-ht,6,2,39)
        for col in range(3):
            bits=mat[(i+2)*4+col+1]
            mask,ink=bits&15,46 if phase==bits>>4 else 47
            h=7
            while mask:
                if mask&1: rect(x+3+col*7,79-ht+h,2,3,ink)
                h+=9;mask>>=1
    rect(L,79,W,1,37)
    return p
base=panorama(-1)
patches,offsets=[],[0]
for phase in range(5):
    p=panorama(phase)
    for y in range(H):
        x=0
        while x<W:
            k=y*W+x
            if p[k]==base[k]:
                x+=1;continue
            assert p[k]==46
            a=x
            while x<W and p[y*W+x]!=base[y*W+x] and p[y*W+x]==46: x+=1
            patches.append((a,y,x-a))
    offsets.append(len(patches))
def rows(values,n=24):
    return "".join(" "+",".join(map(str,values[i:i+n]))+",\n" for i in range(0,len(values),n))
sky="""/* Generated by tools/build_scenery_atlas.py. Exact neutral skyline,
   plus five original window-light phases. No runtime framebuffer. */
"""
sky+=f"static const uint8_t hd_sky_pixels[{W*H}] __attribute__((aligned(4)))={{\n"+rows(base)+"};\n"
sky+="static const uint16_t hd_sky_light_offset[6]={"+",".join(map(str,offsets))+"};\n"
sky+="typedef struct {uint16_t x;uint8_t row,width;} HdSkyLight;\n"
sky+=f"static const HdSkyLight hd_sky_lights[{len(patches)}]={{\n"+"".join(" {"+",".join(map(str,v))+"},\n" for v in patches)+"};\n"
(out/"hd_skyline_rom.inc").write_text(sky)
def texel(x,y):
    n=((x+31)*1664525+(y+79)*1013904223)&0xffffffff
    n=((n^(n>>13))*2246822519)&0xffffffff
    return n^(n>>11)
li,lr,lc,si,sr,sc=[255]*432,[],[],[255]*432,[],[]
for ty,row in enumerate(town):
    for tx,t in enumerate(row):
        if t not in ".#ATg~,=":
            li[ty*24+tx]=len(lr)//16
            def cat(x,y):
                n=texel(tx*16+x,ty*16+y)
                return 0 if n&31==0 else 1 if n&7==1 else 2
            for y in range(16):
                lr.append(sum(cat(x,y)<<(2*x) for x in range(16)))
                lc.append(sum(cat(y,x)<<(2*x) for x in range(16)))
        elif t in "Tg~":
            si[ty*24+tx]=len(sr)//8
            for y in range(8):
                sr.append(sum(int(texel(tx*8+x,ty*8+y)&3==0)<<x for x in range(8)))
                sc.append(sum(int(texel(tx*8+y,ty*8+x)&3==0)<<x for x in range(8)))
def table(name,typ,v,n):
    return f"static const {typ} {name}[{len(v)}]={{\n"+rows(v,n)+"};\n"
atlas="""/* Generated by tools/build_scenery_atlas.py. Exact landmark pavement
   and grass/tree/water hash categories, packed in both scan directions. */
"""
atlas+=table("hd_landmark_floor_index","uint8_t",li,24)+table("hd_landmark_floor_rows","uint32_t",lr,8)+table("hd_landmark_floor_cols","uint32_t",lc,8)
atlas+=table("hd_soft_floor_index","uint8_t",si,24)+table("hd_soft_floor_rows","uint8_t",sr,24)+table("hd_soft_floor_cols","uint8_t",sc,24)
(out/"hd_extra_floor_atlas.inc").write_text(atlas)
