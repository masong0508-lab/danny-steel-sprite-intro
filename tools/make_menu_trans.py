"""Builds src/menu_trans_data.c: the menu's option-select transition (the zoom-through-the-square), taken from the reference video.
Run from project root:  python3 tools/make_menu_trans.py <frames_dir>
frames_dir = every video frame at 50 fps, made by:  ffmpeg -i reference.mp4 -vf fps=50 frames_dir/a%03d.png
  * frames SRC0..SRC1 of the clip are resampled to 30 fps, cropped to the real picture (the video has black bars), shown at 120x80 like the loop
  * the labels / cursor that are baked into the first frames are inpainted away (the game draws them itself as sprites, so they can fade)
  * 3 baked dissolve frames lead back into loop frame 0, so the transition ends on the normal background
  * its own 256-colour palette (the zoom frames are brighter than the loop); the menu swaps palettes in sync with the page flip."""
import sys, re, numpy as np, cv2
from PIL import Image
D = sys.argv[1]
SRC0, SRC1, NCLIP = 208, 224, 11            # video frames 208..224 (4.16 s .. 4.48 s), resampled to NCLIP frames (30 fps)
INPAINT_UP_TO = 216                          # frames up to this one still contain fading labels / cursor
CROP = (37, 0, 603, 360)                     # picture area inside the 640x360 video
XF = [0.25, 0.5, 0.75]                       # dissolve weights toward loop frame 0

def load(i): return Image.open('%s/a%03d.png' % (D, i)).convert('RGB').crop(CROP)
def clean(im, i):
    a = np.array(im); g = cv2.cvtColor(a, cv2.COLOR_RGB2GRAY)
    diff = g.astype(int) - cv2.medianBlur(g, 21).astype(int)
    hsv = cv2.cvtColor(a, cv2.COLOR_RGB2HSV)
    m = ((diff > 10) | (hsv[:, :, 1] > 45)).astype(np.uint8)
    keep = np.zeros_like(m); keep[250:292, 40:540] = 1; keep[150:260, 230:420] = 1      # label row + cursor area (picture coords)
    m = cv2.dilate(m * keep, np.ones((5, 5), np.uint8))
    return Image.fromarray(cv2.inpaint(a, m, 4, cv2.INPAINT_TELEA))

clip = []
for k in range(NCLIP):
    i = SRC0 + round(k * (SRC1 - SRC0) / (NCLIP - 1)); im = load(i)
    if i <= INPAINT_UP_TO: im = clean(im, i)
    clip.append(np.array(im.resize((120, 80), Image.LANCZOS)).astype(np.float32))

def lz_dec(b):                                        # BIOS LZ77 decoder, to read loop frame 0 back out of menu_data.c
    n = b[1] | b[2] << 8 | b[3] << 16; o = bytearray(); i = 4
    while len(o) < n:
        f = b[i]; i += 1
        for bit in range(8):
            if len(o) >= n: break
            if f & (0x80 >> bit):
                l = (b[i] >> 4) + 3; d = ((b[i] & 15) << 8 | b[i + 1]) + 1; i += 2
                for _ in range(l): o.append(o[-d])
            else: o.append(b[i]); i += 1
    return bytes(o[:n])
src = open('src/menu_data.c').read()
pal = [int(x, 16) for x in re.search(r'menu_pal\[256\] = \{([^}]*)\}', src).group(1).split(',')]
z0 = bytes(int(x) for x in re.search(r'z0\[\d+\][^=]*= \{([^}]*)\}', src).group(1).split(','))
rgb = np.array([[(p & 31) * 255 // 31, (p >> 5 & 31) * 255 // 31, (p >> 10 & 31) * 255 // 31] for p in pal], np.float32)
loop0 = rgb[np.frombuffer(lz_dec(z0), np.uint8).reshape(80, 120)]
out = clip + [clip[-1] * (1 - w) + loop0 * w for w in XF]
out = [o.round().astype(np.uint8) for o in out]
sample = np.concatenate([o[::2, ::2].reshape(-1, 3) for o in out]).reshape(-1, 1, 3)
pal_im = Image.fromarray(sample).quantize(256, Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
pl = pal_im.getpalette()[:768]

def lz(data):                                          # GBA BIOS LZ77 (type 0x10), VRAM-safe: displacement >= 2 (same encoder as make_menu.py)
    n = len(data); o = bytearray([0x10, n & 255, n >> 8 & 255, n >> 16 & 255]); i = 0; chains = {}
    while i < n:
        flag_pos = len(o); o.append(0); flag = 0
        for b in range(8):
            if i >= n: break
            best = 0; bd = 0
            if i + 3 <= n:
                for j in reversed(chains.get(bytes(data[i:i + 3]), [])[-24:]):
                    d = i - j
                    if d > 4096: break
                    if d < 2: continue
                    l = 3
                    while l < 18 and i + l < n and data[j + l] == data[i + l]: l += 1
                    if l > best: best, bd = l, d
                    if l == 18: break
            step = best if best >= 3 else 1
            if best >= 3:
                flag |= 0x80 >> b; o.append(((best - 3) << 4) | ((bd - 1) >> 8)); o.append((bd - 1) & 255)
            else: o.append(data[i])
            for k in range(i, i + step):
                if k + 3 <= n: chains.setdefault(bytes(data[k:k + 3]), []).append(k)
            i += step
        o[flag_pos] = flag
    while len(o) % 4: o.append(0)
    return bytes(o)
streams = []
for fr in out:
    idx = np.array(Image.fromarray(fr).quantize(palette=pal_im, dither=Image.Dither.NONE), np.uint8)
    s = lz(idx.tobytes()); assert lz_dec(s) == idx.tobytes(); streams.append(s)
with open('src/menu_trans_data.c', 'w') as f:
    f.write('// GENERATED by tools/make_menu_trans.py - do not edit\n#include "menu.h"\n')
    f.write('const u16 trans_pal[256] = {' + ','.join('0x%04x' % ((pl[i*3] >> 3) | ((pl[i*3+1] >> 3) << 5) | ((pl[i*3+2] >> 3) << 10)) for i in range(256)) + '};\n')
    for i, s in enumerate(streams): f.write('static const u8 t%d[%d] __attribute__((aligned(4))) = {%s};\n' % (i, len(s), ','.join(map(str, s))))
    f.write('const u8 *const trans_bands[%d] = {%s};\n' % (len(streams), ','.join('t%d' % i for i in range(len(streams)))))
    f.write('const int TRANS_FRAMES = %d;\n' % len(streams))
print('frames', len(streams), 'KB', sum(len(s) for s in streams) // 1024)
# preview sheet (not used by the game)
pv = Image.new('RGB', (120 * 7, 80 * 2))
for k, o in enumerate(out): pv.paste(Image.fromarray(o), ((k % 7) * 120, (k // 7) * 80))
pv.save('/tmp/trans_preview.png')
