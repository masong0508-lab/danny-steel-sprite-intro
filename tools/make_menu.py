"""Builds src/menu_data.c: the main-menu video loop.  Run from project root:  python3 tools/make_menu.py [frames_dir]
frames_dir = PNGs (120x80) made by:  ffmpeg -i clip.mp4 -vf "fps=8.5,scale=120:90:flags=lanczos,crop=120:80" f%03d.png
  * one shared 256-colour palette, no dither (LZ77-friendly), each frame = 120x80 (shown 2x by the affine BG), one GBA-BIOS LZ77 stream each
  * the loop crossfade is BAKED IN: the last XF frames blend the clip's tail into its head, so playback just wraps."""
import sys, glob, numpy as np
from PIL import Image
D = sys.argv[1] if len(sys.argv) > 1 else '/tmp/fr2'; XF = 4; BANDS = 1; ROWS = 80
src = [np.array(Image.open(f).convert('RGB')).astype(np.float32) for f in sorted(glob.glob(D + '/f*.png'))]
N = len(src); M = N - XF
out = []
for t in range(M):                                   # frame t<XF: fade from the clip's tail (continuing the last frame) into its head
    if t < XF: a = (t + 1) / (XF + 1); out.append(src[t] * a + src[M + t] * (1 - a))
    else: out.append(src[t])
out = [o.round().astype(np.uint8) for o in out]
sample = np.concatenate([o[::2, ::2].reshape(-1, 3) for o in out[::3]]).reshape(-1, 1, 3)
pal_im = Image.fromarray(sample).quantize(256, Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
pl = pal_im.getpalette()[:768]
def lz(data):                                        # GBA BIOS LZ77 (type 0x10), VRAM-safe: displacement >= 2
    n = len(data); o = bytearray([0x10, n & 255, n >> 8 & 255, n >> 16 & 255]); i = 0; chains = {}
    while i < n:
        flag_pos = len(o); o.append(0); flag = 0
        for b in range(8):
            if i >= n: break
            best = 0; bd = 0
            if i + 3 <= n:
                for j in reversed(chains.get(bytes(data[i:i + 3]), [])[-24:]):
                    d = i - j
                    if d > 4096: break
                    if d < 2: continue
                    l = 3
                    while l < 18 and i + l < n and data[j + l] == data[i + l]: l += 1
                    if l > best: best, bd = l, d
                    if l == 18: break
            step = best if best >= 3 else 1
            if best >= 3:
                flag |= 0x80 >> b; o.append(((best - 3) << 4) | ((bd - 1) >> 8)); o.append((bd - 1) & 255)
            else: o.append(data[i])
            for k in range(i, i + step):
                if k + 3 <= n: chains.setdefault(bytes(data[k:k + 3]), []).append(k)
            i += step
        o[flag_pos] = flag
    while len(o) % 4: o.append(0)
    return bytes(o)
streams = []
for fr in out:
    idx = np.array(Image.fromarray(fr).quantize(palette=pal_im, dither=Image.Dither.NONE), np.uint8)
    for b in range(BANDS): streams.append(lz(idx[b * ROWS:(b + 1) * ROWS].tobytes()))
tot = sum(len(s) for s in streams)
with open('src/menu_data.c', 'w') as f:
    f.write('// GENERATED by tools/make_menu.py - do not edit\n#include "menu.h"\n')
    f.write('const u16 menu_pal[256] = {' + ','.join('0x%04x' % ((pl[i*3] >> 3) | ((pl[i*3+1] >> 3) << 5) | ((pl[i*3+2] >> 3) << 10)) for i in range(256)) + '};\n')
    for i, s in enumerate(streams): f.write('static const u8 z%d[%d] __attribute__((aligned(4))) = {%s};\n' % (i, len(s), ','.join(map(str, s))))
    f.write('const u8 *const menu_bands[%d] = {%s};\n' % (len(streams), ','.join('z%d' % i for i in range(len(streams)))))
    f.write('const int MENU_FRAMES = %d;\n' % M)
print('frames', M, 'bytes', tot, 'KB', tot // 1024)
