#!/usr/bin/env python3
"""Transpose the exact existing 2-bit material categories into packed columns."""
from pathlib import Path
import re
import sys

source = Path("src/hd_road_material_rom.inc").read_text()
section = source.split("static const uint8_t hd_road_material_2bits", 1)[1]
packed = [int(v) for v in re.findall(r"\d+", section.split("{", 1)[1].split("};", 1)[0])]
assert len(packed) == 240 * 64
columns = []
for tile in range(240):
    for x in range(16):
        word = 0
        for y in range(16):
            category = (packed[tile * 64 + y * 4 + (x >> 2)] >> ((x & 3) * 2)) & 3
            word |= category << (y * 2)
        columns.append(word)
result = "/* Generated by tools/build_road_columns.py from the existing two-bit road rows.\n   15,360 ROM bytes, zero additional RAM. One load per crossed road tile. */\n"
result += "static const uint32_t hd_road_columns[240u*16u]={\n"
for i in range(0, len(columns), 8):
    result += " " + ",".join(f"0x{x:08x}u" for x in columns[i:i + 8]) + ",\n"
result += "};\n"
Path(sys.argv[1] if len(sys.argv) > 1 else "src/hd_road_columns.inc").write_text(result)
